// Smart Curriculum Matcher Function with Fuzzy Token Scoring
function findCurriculumMatch(selectedSubject, selectedGrade, query) {
    if (!query || typeof query !== 'string') return null;
    const cleanQuery = query.toLowerCase().trim();
    if (cleanQuery.length < 2) return null;

    const queryTokens = cleanQuery.split(/[\s,.:;—–\(\)\[\]«»"']+/).filter(t => t.length >= 2);
    if (queryTokens.length === 0) return null;

    let bestMatch = null;
    let highestScore = 0;

    for (let item of KAZAKHSTAN_CURRICULUM_DB) {
        let score = 0;
        const isExactSubject = item.subject.toLowerCase() === (selectedSubject || '').toLowerCase();
        const isExactGrade = item.grade.toLowerCase().includes((selectedGrade || '').replace(/[^0-9]/g, ''));

        // Subject Match Bonus
        if (isExactSubject) score += 30;
        if (isExactGrade && isExactSubject) score += 20;

        // Check against Keywords
        for (let kw of item.keywords) {
            const kwLower = kw.toLowerCase();
            if (cleanQuery === kwLower || cleanQuery.includes(kwLower)) {
                score += 50;
            } else {
                for (let token of queryTokens) {
                    if (kwLower === token) {
                        score += 35;
                    } else if (kwLower.includes(token) || token.includes(kwLower)) {
                        score += 20;
                    }
                }
            }
        }

        // Check against Topic title and Unit
        const topicLower = item.topic.toLowerCase();
        const unitLower = item.unit.toLowerCase();
        for (let token of queryTokens) {
            if (topicLower.includes(token)) score += 15;
            if (unitLower.includes(token)) score += 10;
        }

        if (score > highestScore && score >= 35) {
            highestScore = score;
            bestMatch = { ...item, matchScore: score };
        }
    }

    return bestMatch;
}
