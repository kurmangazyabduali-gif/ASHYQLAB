async function fetchFastAIText(prompt) {
    const effectivePollKey = (API_KEY && API_KEY.startsWith('sk-')) ? API_KEY : USER_POLLINATIONS_KEY;
    try {
        const res = await fetch('https://gen.pollinations.ai/v1/chat/completions', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                'Authorization': `Bearer ${effectivePollKey}`
            },
            body: JSON.stringify({
                model: 'openai',
                messages: [{ role: 'user', content: prompt }],
                temperature: 0.4
            })
        });
        if (res.ok) {
            const data = await res.json();
            return data?.choices?.[0]?.message?.content;
        }
    } catch (e) {
        console.warn('Pollinations chat failed, fallback to Gemini...', e);
    }

    const activeGeminiKey = (API_KEY && (API_KEY.startsWith('AQ.') || API_KEY.startsWith('AIzaSy'))) ? API_KEY : FALLBACK_GEMINI_KEY;
    const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${activeGeminiKey}`;
    const res = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
            contents: [{ parts: [{ text: prompt }] }],
            generationConfig: { temperature: 0.4 }
        })
    });
    const data = await res.json();
    return data?.candidates?.[0]?.content?.parts?.[0]?.text;
}

function safeParseJson(str) {
    try {
        let clean = String(str).trim();
        if (clean.startsWith('```json')) clean = clean.slice(7);
        if (clean.startsWith('```')) clean = clean.slice(3);
        if (clean.endsWith('```')) clean = clean.slice(0, -3);
        clean = clean.trim();
        return JSON.parse(clean);
    } catch (e) {
        return null;
    }
}

